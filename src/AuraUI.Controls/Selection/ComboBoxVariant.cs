namespace AuraUI.Controls.Selection;

/// <summary>
/// Visual variant for an <see cref="AuraComboBox"/> control.
/// </summary>
public enum ComboBoxVariant
{
    /// <summary>
    /// Outlined / bordered styling (default).
    /// </summary>
    Outlined,

    /// <summary>
    /// Filled background styling.
    /// </summary>
    Filled,

    /// <summary>
    /// Underlined styling with a bottom border only.
    /// </summary>
    Underlined
}
