namespace AuraUI.Controls.Layout;

/// <summary>
/// Shape variant for a <see cref="Skeleton"/> placeholder.
/// </summary>
public enum SkeletonVariant
{
    /// <summary>
    /// Text placeholder (one or more lines).
    /// </summary>
    Text,

    /// <summary>
    /// Circular placeholder (e.g. avatar).
    /// </summary>
    Circle,

    /// <summary>
    /// Rectangular placeholder.
    /// </summary>
    Rect,

    /// <summary>
    /// Image placeholder (wider rectangle).
    /// </summary>
    Image
}
