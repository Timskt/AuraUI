namespace AuraUI.Controls.Layout;

/// <summary>
/// Visual variant for a <see cref="Tag"/> control.
/// </summary>
public enum TagVariant
{
    /// <summary>
    /// Default styling.
    /// </summary>
    Default,

    /// <summary>
    /// Primary theme color.
    /// </summary>
    Primary,

    /// <summary>
    /// Success / positive color.
    /// </summary>
    Success,

    /// <summary>
    /// Warning color.
    /// </summary>
    Warning,

    /// <summary>
    /// Error / danger color.
    /// </summary>
    Error,

    /// <summary>
    /// Outlined / bordered styling.
    /// </summary>
    Outlined
}
