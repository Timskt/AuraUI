namespace AuraUI.Controls.Layout;

/// <summary>
/// Specifies the direction in which an <see cref="Expander"/> control opens.
/// </summary>
public enum ExpandDirection
{
    /// <summary>
    /// The expander opens downward.
    /// </summary>
    Down,

    /// <summary>
    /// The expander opens upward.
    /// </summary>
    Up,

    /// <summary>
    /// The expander opens to the left.
    /// </summary>
    Left,

    /// <summary>
    /// The expander opens to the right.
    /// </summary>
    Right
}
